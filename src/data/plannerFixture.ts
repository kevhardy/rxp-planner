export function zonePoint(
  zone: { id: number; uiMapId: number },
  x: number,
  y: number,
  from: Pick<QuestPoint, "kind" | "sourceType" | "sourceId" | "sourceName">,
): QuestPoint {
  const placed = percentToWorld([MAP_BOUNDS.get(zone.uiMapId)], x, y);
  if (!placed.ok) throw new Error(placed.reason);
  return { zoneId: zone.id, uiMapId: zone.uiMapId, x, y, world: placed.world, ...from };
}

